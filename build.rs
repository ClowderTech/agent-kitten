use std::fs;
use std::path::Path;

const GEN_FILE: &str = "modules.rs";

fn main() {
    println!("cargo::rerun-if-changed=src");
    println!("cargo::rerun-if-changed=build.rs");

    let src = Path::new("src");

    let mut subdirs: Vec<String> = Vec::new();
    let mut files: Vec<String> = Vec::new();
    for entry in fs::read_dir(src).unwrap() {
        let path = entry.unwrap().path();
        let name = path.file_name().unwrap().to_string_lossy().to_string();
        if name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            subdirs.push(name);
        } else if name.ends_with(".rs") && name != "main.rs" && name != GEN_FILE {
            files.push(name);
        }
    }
    subdirs.sort();
    files.sort();

    let mut commands: Vec<String> = Vec::new();

    let mut out = String::new();
    out.push_str("// This file is auto-generated by build.rs. Do not edit.\n");
    out.push_str("// Declares every module under src/ via #[path] so no mod.rs files are needed.\n");
    out.push_str("// Included from main.rs, so these land at the crate root (crate::entity, crate::commands, ...).\n\n");

    // Subdirectory modules (commands, entity, ...) as inline #[path] modules.
    // The `commands` tree doubles as the poise command registry.
    for name in &subdirs {
        let is_commands = name == "commands";
        out.push_str(&format!("#[path = \"{name}\"]\npub mod {name} {{\n"));
        gen_children(
            &src.join(name),
            1,
            &format!("crate::{name}"),
            is_commands,
            &mut out,
            &mut commands,
        );
        out.push_str("}\n\n");
    }

    // Top-level file modules (helpers, events, ...).
    for name in &files {
        let stem = stem(name);
        out.push_str(&format!("#[path = \"{name}\"]\npub mod {stem};\n\n"));
    }

    out.push_str("pub fn all_commands() -> Vec<poise::Command<crate::Data, crate::Error>> {\n    vec![\n");
    for cmd in &commands {
        let func = cmd.rsplit("::").next().unwrap();
        out.push_str(&format!("        {cmd}::{func}(),\n"));
    }
    out.push_str("    ]\n}\n");

    write_if_changed(&src.join(GEN_FILE), &out);
}

/// Emit `#[path]`-based declarations for everything inside `dir`.
///
/// `ident_prefix` is the full Rust path to this module (e.g. `crate::commands::music`).
/// When `collect_commands` is set (the `commands` tree), each file's command function is
/// recorded for `all_commands`.
fn gen_children(
    dir: &Path,
    indent: usize,
    ident_prefix: &str,
    collect_commands: bool,
    out: &mut String,
    commands: &mut Vec<String>,
) {
    let mut subdirs: Vec<String> = Vec::new();
    let mut files: Vec<String> = Vec::new();
    for entry in fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        let name = path.file_name().unwrap().to_string_lossy().to_string();
        if name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            subdirs.push(name);
        } else if name.ends_with(".rs") && name != "mod.rs" {
            files.push(name);
        }
    }
    subdirs.sort();
    files.sort();

    let pad = "    ".repeat(indent);

    for name in &files {
        let stem = stem(name);
        out.push_str(&format!("{pad}#[path = \"{name}\"]\n{pad}pub mod {stem};\n"));
        if collect_commands {
            commands.push(format!("{ident_prefix}::{stem}"));
        }
    }

    for name in &subdirs {
        out.push_str(&format!("{pad}#[path = \"{name}\"]\n{pad}pub mod {name} {{\n"));
        gen_children(
            &dir.join(name),
            indent + 1,
            &format!("{ident_prefix}::{name}"),
            collect_commands,
            out,
            commands,
        );
        out.push_str(&format!("{pad}}}\n"));
    }
}

fn stem(name: &str) -> &str {
    &name[..name.len() - ".rs".len()]
}

/// Write only when content differs, so the generated file's mtime stays stable and
/// `cargo::rerun-if-changed=src` doesn't trigger an endless rebuild loop.
fn write_if_changed(path: &Path, contents: &str) {
    if let Ok(existing) = fs::read_to_string(path)
        && existing == contents
    {
        return;
    }
    fs::write(path, contents).expect("Could not write generated modules file");
}
